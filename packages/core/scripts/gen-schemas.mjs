// Generates src/schemas.gen.ts from schemas/clickless.schema.json.
// Definitions must appear in the schema file before anything that references them.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { jsonSchemaToZod } from "json-schema-to-zod";
import { findRepositoryRoot } from "./repositoryRoot.mjs";

const schemaPath = join(findRepositoryRoot(), "schemas", "clickless.schema.json");
const outPath = fileURLToPath(new URL("../src/schemas.gen.ts", import.meta.url));

const { $defs } = JSON.parse(readFileSync(schemaPath, "utf8"));
const refName = (ref) => {
  const match = /^#\/\$defs\/(\w+)$/.exec(ref);
  if (!match || !(match[1] in $defs)) throw new Error(`Unsupported $ref: ${ref}`);
  return match[1];
};

const seen = new Set();
const blocks = Object.entries($defs).map(([name, def]) => {
  const code = jsonSchemaToZod(def, {
    parserOverride: (node) => {
      if (typeof node.$ref !== "string") return undefined;
      const target = refName(node.$ref);
      if (!seen.has(target)) throw new Error(`${name} references ${target} before it is defined`);
      return target;
    },
  });
  seen.add(name);
  return `export const ${name} = ${code};\nexport type ${name} = z.infer<typeof ${name}>;`;
});

writeFileSync(
  outPath,
  `// Generated by scripts/gen-schemas.mjs from schemas/clickless.schema.json. Do not edit.\nimport { z } from "zod";\n\n${blocks.join("\n\n")}\n`,
);
console.log(`wrote ${outPath}`);
